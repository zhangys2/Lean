#!/usr/bin/env bash
# Cursor Cloud Agent install for Lean. Idempotent. Runs from the repo root.
# Installs .NET SDK 10.0.402, a uv CPython 3.11 venv, and Release-builds the solution.
# Shell exports do not survive a Cloud Agent snapshot, so the pythonnet variables
# are written to ~/.config/lean-cursor-env.sh and sourced from ~/.bashrc and ~/.profile.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

SETUP="${HOME}/tmp/lean-cursor-setup"
VENV="${LEAN_PY_VENV:-${HOME}/.local/share/lean-py311}"
CPUS="${LEAN_MAX_CPU:-2}"
ENV_FILE="${HOME}/.config/lean-cursor-env.sh"

mkdir -p "$SETUP" "${HOME}/.config" "${HOME}/.local/bin"

export DOTNET_CLI_TELEMETRY_OPTOUT=1
export DOTNET_NOLOGO=1
export DOTNET_ROOT="${HOME}/.dotnet"
export PATH="${DOTNET_ROOT}:${HOME}/.local/bin:${PATH}"

run_nice() {
  if command -v ionice >/dev/null 2>&1; then
    nice -n 19 ionice -c3 "$@"
  else
    nice -n 19 "$@"
  fi
}

if ! "${DOTNET_ROOT}/dotnet" --list-sdks 2>/dev/null | awk '{print $1}' | grep -qx '10.0.402'; then
  curl -fsSL https://dot.net/v1/dotnet-install.sh -o "${SETUP}/dotnet-install.sh"
  bash "${SETUP}/dotnet-install.sh" --version 10.0.402 --install-dir "$DOTNET_ROOT"
fi

if ! command -v uv >/dev/null 2>&1; then
  curl -LsSf https://astral.sh/uv/install.sh | sh
  export PATH="${HOME}/.local/bin:${PATH}"
fi

uv python install 3.11
if [[ ! -x "${VENV}/bin/python" ]]; then
  uv venv --python 3.11 "$VENV"
fi
uv pip install --python "${VENV}/bin/python" 'pandas==2.3.3' 'numpy==1.26.4' 'wrapt==1.17.3'
"${VENV}/bin/python" -c 'import pandas, numpy, wrapt; print(pandas.__version__, numpy.__version__, wrapt.__version__)'

real_py="$(readlink -f "${VENV}/bin/python")"
prefix="$(cd "$(dirname "$real_py")/.." && pwd)"
pydll=""
for cand in "${prefix}/lib/libpython3.11.so" "${prefix}/lib/libpython3.11.so.1.0"; do
  if [[ -e "$cand" ]]; then
    pydll="$cand"
    break
  fi
done
if [[ -z "$pydll" ]]; then
  echo "libpython3.11 not found under ${prefix}/lib" >&2
  exit 1
fi
site="$("${VENV}/bin/python" -c 'import site; print(site.getsitepackages()[0])')"

cat > "$ENV_FILE" <<EOF
# Generated by .cursor/install.sh. Safe to re-source.
export DOTNET_ROOT='${DOTNET_ROOT}'
export DOTNET_CLI_TELEMETRY_OPTOUT=1
case ":\${PATH}:" in
  *":\${DOTNET_ROOT}:"*) ;;
  *) export PATH="\${DOTNET_ROOT}:${HOME}/.local/bin:\${PATH}" ;;
esac
export PYTHONNET_PYDLL='${pydll}'
if [ -z "\${PYTHONPATH:-}" ]; then
  export PYTHONPATH='${site}'
fi
EOF

source_line='[ -f "$HOME/.config/lean-cursor-env.sh" ] && . "$HOME/.config/lean-cursor-env.sh"'
for rc in "${HOME}/.bashrc" "${HOME}/.profile"; do
  touch "$rc"
  if ! grep -q 'lean-cursor-env.sh' "$rc"; then
    printf '\n# Lean pythonnet (Cursor Cloud Agents)\n%s\n' "$source_line" >> "$rc"
  fi
done

ln -sfn "${DOTNET_ROOT}/dotnet" "${HOME}/.local/bin/dotnet"

# shellcheck disable=SC1090
. "$ENV_FILE"

run_nice "${DOTNET_ROOT}/dotnet" restore QuantConnect.Lean.sln --verbosity minimal
run_nice "${DOTNET_ROOT}/dotnet" build QuantConnect.Lean.sln -c Release --no-restore --maxcpucount:"${CPUS}" --verbosity minimal

echo "install ok: SDK $(${DOTNET_ROOT}/dotnet --version) PYTHONNET_PYDLL=${pydll}"
